// License tooling shared by generate-keypair.mjs and generate-license.mjs.
//
// Plain JavaScript using only Node.js built-ins, so it runs on any PC with Node installed
// (Windows, macOS, Linux) WITHOUT `npm install`. It must stay byte-compatible with the
// app's verifier in src/main/license/core.ts — tests/license-tools.test.ts checks that.
//
// License format:  AIHUB1.<base64url(JSON payload)>.<base64url(Ed25519 signature)>
// The signature covers the text "AIHUB1.<payload segment>".
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const LICENSE_PREFIX = 'AIHUB1'
export const PRODUCT_ID = 'ai-hub'

/** The public key committed in the repository whose private key was destroyed. */
export const PLACEHOLDER_PUBLIC_KEY = 'MCowBQYDK2VwAyEAUd4kdER+Z6hv0VG4X1XCDRZtqdNgIU6rsBz/dMmoSMc='

/** Repository root (the folder that contains tools/). */
export const DEFAULT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

export function paths(root = DEFAULT_ROOT) {
  const keysDir = path.join(root, 'keys')
  return {
    keysDir,
    privateKey: path.join(keysDir, 'license-private.pem'),
    publicKeyPem: path.join(keysDir, 'license-public.pem'),
    issuedLog: path.join(keysDir, 'issued-licenses.csv'),
    publicKeyTs: path.join(root, 'src', 'main', 'license', 'publicKey.ts')
  }
}

/** Source of src/main/license/publicKey.ts (LF line endings, Prettier formatted). */
export function publicKeyModuleSource(publicKeyPem) {
  const pem = publicKeyPem.replace(/\r\n/g, '\n').trim()
  return [
    '/**',
    ' * Ed25519 PUBLIC key used to verify license keys offline.',
    ' *',
    ' * Generated by tools/generate-keypair.mjs. The matching PRIVATE key is in',
    ' * keys/license-private.pem on the seller’s PC — it must never be committed or shared.',
    ' */',
    '// BEGIN-PUBLIC-KEY',
    `export const LICENSE_PUBLIC_KEY_PEM = \`${pem}`,
    '`',
    '// END-PUBLIC-KEY',
    ''
  ].join('\n')
}

/** Read the PEM embedded in publicKey.ts (works with CRLF or LF files). */
export function readEmbeddedPublicKey(root = DEFAULT_ROOT) {
  const src = fs.readFileSync(paths(root).publicKeyTs, 'utf8')
  const m = /-----BEGIN PUBLIC KEY-----[\s\S]*?-----END PUBLIC KEY-----/.exec(src)
  if (!m) throw new Error(`No public key found in ${paths(root).publicKeyTs}`)
  return `${m[0].replace(/\r\n/g, '\n')}\n`
}

export function isPlaceholderKey(root = DEFAULT_ROOT) {
  return readEmbeddedPublicKey(root).includes(PLACEHOLDER_PUBLIC_KEY)
}

/**
 * Create a new keypair: writes keys/license-private.pem (+ license-public.pem) and rewrites
 * src/main/license/publicKey.ts. Refuses to replace an existing private key unless force.
 */
export function createKeypair(root = DEFAULT_ROOT, { force = false } = {}) {
  const p = paths(root)
  if (fs.existsSync(p.privateKey) && !force) {
    const err = new Error(
      `A private key already exists at ${p.privateKey}. Use --force to replace it ` +
        '(licenses made with the old key will stop working in new builds).'
    )
    err.code = 'KEY_EXISTS'
    throw err
  }
  if (!fs.existsSync(p.publicKeyTs)) {
    throw new Error(`Cannot find ${p.publicKeyTs}. Run this from inside the AI Hub folder.`)
  }
  const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519')
  const publicKeyPem = publicKey.export({ type: 'spki', format: 'pem' }).toString()
  const privateKeyPem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString()
  fs.mkdirSync(p.keysDir, { recursive: true })
  fs.writeFileSync(p.privateKey, privateKeyPem, { mode: 0o600 })
  fs.writeFileSync(p.publicKeyPem, publicKeyPem)
  fs.writeFileSync(p.publicKeyTs, publicKeyModuleSource(publicKeyPem))
  return { ...p, publicKeyPemText: publicKeyPem }
}

export function signLicense(payload, privateKeyPem) {
  const body = Buffer.from(JSON.stringify(payload), 'utf8').toString('base64url')
  const signingInput = `${LICENSE_PREFIX}.${body}`
  const sig = crypto.sign(
    null,
    Buffer.from(signingInput, 'utf8'),
    crypto.createPrivateKey(privateKeyPem)
  )
  return `${signingInput}.${sig.toString('base64url')}`
}

/** Minimal verifier (same rules as the app) used to self-check issued keys. */
export function verifyLicense(key, publicKeyPem) {
  const parts = key.replace(/\s+/g, '').split('.')
  if (parts.length !== 3 || parts[0] !== LICENSE_PREFIX) return false
  try {
    return crypto.verify(
      null,
      Buffer.from(`${parts[0]}.${parts[1]}`, 'utf8'),
      crypto.createPublicKey(publicKeyPem),
      Buffer.from(parts[2], 'base64url')
    )
  } catch {
    return false
  }
}

function csvField(value) {
  const s = String(value ?? '')
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
}

/**
 * Issue a license key. Returns { key, payload, matchesApp } where matchesApp tells whether the
 * key verifies against the public key currently embedded in the app source.
 */
export function issueLicense(root = DEFAULT_ROOT, { name, email, id, expires, keyPath } = {}) {
  const p = paths(root)
  if (!name || !String(name).trim()) throw new Error('A buyer name is required (--name).')
  const privPath = keyPath ? path.resolve(keyPath) : p.privateKey
  if (!fs.existsSync(privPath)) {
    const err = new Error(
      `Private key not found at ${privPath}. Run "npm run license:keypair" first.`
    )
    err.code = 'NO_PRIVATE_KEY'
    throw err
  }
  let expiresAt
  if (expires) {
    const d = new Date(expires)
    if (Number.isNaN(d.getTime()))
      throw new Error(`Invalid --expires date: ${expires} (use YYYY-MM-DD)`)
    expiresAt = d.toISOString()
  }
  const payload = {
    v: 1,
    product: PRODUCT_ID,
    id:
      id && String(id).trim()
        ? String(id).trim()
        : `LIC-${crypto.randomBytes(5).toString('hex').toUpperCase()}`,
    name: String(name).trim(),
    ...(email && String(email).trim() ? { email: String(email).trim() } : {}),
    issuedAt: new Date().toISOString(),
    ...(expiresAt ? { expiresAt } : {})
  }
  const key = signLicense(payload, fs.readFileSync(privPath, 'utf8'))

  let matchesApp = false
  try {
    matchesApp = verifyLicense(key, readEmbeddedPublicKey(root))
  } catch {
    matchesApp = false
  }

  fs.mkdirSync(path.dirname(p.issuedLog), { recursive: true })
  if (!fs.existsSync(p.issuedLog))
    fs.writeFileSync(p.issuedLog, 'issuedAt,id,name,email,expiresAt\n')
  fs.appendFileSync(
    p.issuedLog,
    [payload.issuedAt, payload.id, payload.name, payload.email, payload.expiresAt]
      .map(csvField)
      .join(',') + '\n'
  )
  return { key, payload, matchesApp, logFile: p.issuedLog }
}

/** Tiny --flag value parser. Flags without a value become true. */
export function parseArgs(argv) {
  const out = {}
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (!a.startsWith('--')) continue
    const name = a.slice(2)
    const next = argv[i + 1]
    if (next === undefined || next.startsWith('--')) out[name] = true
    else {
      out[name] = next
      i++
    }
  }
  return out
}
