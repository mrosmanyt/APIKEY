/**
 * Creates your Ed25519 license-signing keypair. Run ONCE:
 *
 *   npm run license:keypair
 *
 * - Writes the PRIVATE key to keys/license-private.pem (git-ignored). Back it up somewhere safe
 *   (password manager / encrypted USB). Anyone with it can create licenses; if you lose it you
 *   cannot create licenses that existing installs accept.
 * - Rewrites src/main/license/publicKey.ts with the matching PUBLIC key. Rebuild the app after.
 *
 * Refuses to overwrite an existing private key unless you pass --force.
 */
import fs from 'node:fs'
import path from 'node:path'
import { generateKeyPair } from '../src/main/license/core'

const root = path.resolve(__dirname, '..')
const keysDir = path.join(root, 'keys')
const privatePath = path.join(keysDir, 'license-private.pem')
const publicTs = path.join(root, 'src/main/license/publicKey.ts')
const force = process.argv.includes('--force')

if (fs.existsSync(privatePath) && !force) {
  console.error(`A private key already exists at ${privatePath}.`)
  console.error('Re-run with --force to replace it (old licenses will stop working in new builds).')
  process.exit(1)
}

const { publicKeyPem, privateKeyPem } = generateKeyPair()
fs.mkdirSync(keysDir, { recursive: true })
fs.writeFileSync(privatePath, privateKeyPem, { mode: 0o600 })
fs.writeFileSync(path.join(keysDir, 'license-public.pem'), publicKeyPem)

const src = fs.readFileSync(publicTs, 'utf8')
const updated = src.replace(
  /\/\/ BEGIN-PUBLIC-KEY[\s\S]*\/\/ END-PUBLIC-KEY/,
  `// BEGIN-PUBLIC-KEY\nexport const LICENSE_PUBLIC_KEY_PEM = \`${publicKeyPem}\`\n// END-PUBLIC-KEY`
)
fs.writeFileSync(
  publicTs,
  updated.replace(
    /⚠️ {2}This is a PLACEHOLDER[\s\S]*?\n \*\//,
    'Generated by tools/generate-keypair.ts. Keep keys/license-private.pem secret.\n */'
  )
)

console.log('✔ Private key written to', privatePath, '(KEEP THIS SECRET, BACK IT UP)')
console.log('✔ Public key embedded in', publicTs)
console.log('\nNext: rebuild the app (npm run build:win) and create licenses with:')
console.log('  npm run license:generate -- --name "Buyer Name" --email buyer@example.com')
